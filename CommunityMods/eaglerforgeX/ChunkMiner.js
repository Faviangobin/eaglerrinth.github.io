/**
 * Compute the oriented rectangular prism (axis-aligned in local forward/right/up space)
 * that represents the trench volume to break, given:
 *   - player position (x,y,z)
 *   - yaw, pitch (degrees)
 *   - trench dimensions (xWidth, yHeight, zDepth) where x is horizontal-left-right, y is vertical, z is forward depth
 *
 * Important rules:
 *   - Never include blocks whose global Y (blockY) is < Math.floor(playerY).
 *   - If pitch is strongly downward, shift box forward/down but still exclude below player's Y.
 *
 * Returns an array of block coordinates to consider breaking: [{x,y,z},...]
 */
function computeTrenchBoxBlocks(world, playerPos, yawDeg, pitchDeg, dims) {
  // Convert yaw/pitch to forward/right/up vectors (unit)
  const yaw = yawDeg * Math.PI / 180;
  const pitch = pitchDeg * Math.PI / 180;

  // forward vector
  const fx = -Math.sin(yaw) * Math.cos(pitch);
  const fy = -Math.sin(pitch);
  const fz = Math.cos(yaw) * Math.cos(pitch);

  // approximate right vector (perpendicular to forward)
  const rx = Math.cos(yaw);
  const rz = Math.sin(yaw);
  const ry = 0;

  // up vector cross product of right and forward
  const ux = fy * rz - fz * ry;
  const uy = fz * rx - fx * rz;
  const uz = fx * ry - fy * rx;
  // normalize up (approx)
  const upLen = Math.sqrt(ux*ux + uy*uy + uz*uz) || 1;
  const uxN = ux / upLen, uyN = uy / upLen, uzN = uz / upLen;

  // We'll iterate integer offsets inside local box coordinates and map to world coordinates.
  // dims.x: horizontal width (we'll center it around 0), dims.y: vertical height (we'll center on player's y or slightly above),
  // dims.z: depth forward (starting from the block the player is looking at or from player's feet forward).

  // Determine base origin: the nearest block in front of player at player's Y (clamped)
  const playerBlockY = Math.floor(playerPos.y);
  // We'll start from player's eye-level / feet depending on pitch.
  const startX = Math.floor(playerPos.x);
  const startY = playerBlockY; // trench will not include below this
  const startZ = Math.floor(playerPos.z);

  // We'll compute center offsets: x offsets in [-halfX..halfX], y offsets [0..dims.y-1] (no below), z offsets [1..dims.z] forward
  const halfX = Math.floor(dims.x / 2);
  const halfZ = Math.floor(dims.z); // depth starting forward (1..dims.z)

  const blocks = [];

  // For each local coordinate, map to world coordinate
  for (let lx = -halfX; lx <= halfX; lx++) {
    for (let lz = 1; lz <= dims.z; lz++) {
      for (let ly = 0; ly < dims.y; ly++) {
        // local vector = rx*lx + ux*ly + fx*lz
        const worldDX = rx * lx + uxN * ly + fx * lz;
        const worldDY = ry * lx + uyN * ly + fy * lz;
        const worldDZ = rz * lx + uzN * ly + fz * lz;

        const bx = Math.floor(playerPos.x + worldDX + 0.5);
        const by = Math.floor(playerPos.y + worldDY); // floor ensures we clamp below separately
        const bz = Math.floor(playerPos.z + worldDZ + 0.5);

        // Enforce not below player's Y coordinate
        if (by < playerBlockY) continue;

        // Avoid duplicates
        const key = bx + "," + by + "," + bz;
        blocks.push({ x: bx, y: by, z: bz, key: key });
      }
    }
  }

  // De-duplicate
  const unique = {};
  const result = [];
  blocks.forEach(b => {
    if (!unique[b.key]) {
      unique[b.key] = true;
      result.push({ x: b.x, y: b.y, z: b.z });
    }
  });

  return result;
}

/* =========================
   HELPER: compute max points by tier
   ========================= */
function computeMaxPointsForTier(tierIndex) {
  // tierIndex: 1..5 (1 wood, 5 diamond). Apply linear scaling:
  // points = WOOD_MAX_POINTS + (DIAMOND_MAX_POINTS - WOOD_MAX_POINTS) * ((tierIndex - 1) / (5 - 1))
  const ratio = (tierIndex - 1) / (5 - 1);
  const points = WOOD_MAX_POINTS + (DIAMOND_MAX_POINTS - WOOD_MAX_POINTS) * ratio;
  // Round to integer
  return Math.floor(points);
}

