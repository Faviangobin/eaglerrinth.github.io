function getBlockAt(world, x, y, z) {
  if (typeof world.getBlock === "function") return world.getBlock(x, y, z);
  // fallback: return a dummy object
  return { id: "minecraft:stone", hardness: 1.5, name: "Stone" };
}

function canHarvestBlockWithMaterial(block, materialId) {
  // Simplified mapping: wood/stone can't harvest diamond ore; iron/diamond can. Gold acts like wood in harvest level on many 1.8 contexts.
  const harvestLevels = {
    "minecraft:diamond_ore": 3,
    "minecraft:gold_ore": 2,
    "minecraft:iron_ore": 1,
    "minecraft:coal_ore": 0,
    "minecraft:stone": 0,
    "minecraft:obsidian": 3
  };
  const required = harvestLevels[block.id] !== undefined ? harvestLevels[block.id] : 0;
  const matLevel = materialId === "wood" ? 0 : materialId === "stone" ? 1 : materialId === "iron" ? 2 : materialId === "gold" ? 0 : 3;
  return matLevel >= required;
}

function estimateDropRisk(world, x, y, z) {
  // Very rough estimation: count empty blocks beneath within 6 blocks
  let risk = 0;
  for (let d = 1; d <= 6; d++) {
    const b = getBlockAt(world, x, y - d, z);
    if (!b || b.id === "minecraft:air") risk++;
    else break;
  }
  return risk;
}

function isBlockOre(block) {
  return block.id && (block.id.indexOf("_ore") !== -1 || block.id.indexOf("ore") !== -1);
}

function attemptVeinBreak(world, x, y, z, veinLevel) {
  // naive BFS up to a small radius; returns array of block coords to add
  const found = [];
  const visited = {};
  const stack = [{ x: x, y: y, z: z }];
  const maxNodes = 8 + veinLevel * 8;
  while (stack.length && found.length < maxNodes) {
    const c = stack.pop();
    const key = c.x + "," + c.y + "," + c.z;
    if (visited[key]) continue;
    visited[key] = true;
    const b = getBlockAt(world, c.x, c.y, c.z);
    if (!b) continue;
    if (isBlockOre(b)) {
      found.push({ x: c.x, y: c.y, z: c.z, block: b });
      // push neighbors
      const nbs = [
        { x: c.x+1, y: c.y, z: c.z }, { x: c.x-1, y: c.y, z: c.z },
        { x: c.x, y: c.y+1, z: c.z }, { x: c.x, y: c.y-1, z: c.z },
        { x: c.x, y: c.y, z: c.z+1 }, { x: c.x, y: c.y, z: c.z-1 }
      ];
      nbs.forEach(nb => {
        if (!visited[nb.x + "," + nb.y + "," + nb.z]) stack.push(nb);
      });
    }
  }
  return found;
}

function breakBlockWithDrops(world, x, y, z, player, dropItems) {
  // Placeholder: call world.breakBlock or similar
  if (typeof world.breakBlock === "function") {
    try {
      world.breakBlock(x, y, z, dropItems);
      return true;
    } catch (e) {
      return false;
    }
  } else {
    // simulate by logging
    console.log("Breaking block at", x, y, z, "dropItems:", dropItems);
    return true;
  }
}

function dropXp(world, x, y, z, amount) {
  if (typeof world.spawnXp === "function") {
    world.spawnXp(x, y, z, amount);
  } else {
    console.log("Drop XP", amount, "at", x, y, z);
  }
}

function reduceItemDurability(itemStack, amount) {
  // Placeholder: many loaders provide itemStack.damage(amount)
  if (typeof itemStack.damage === "function") {
    itemStack.damage(amount);
  } else {
    // fallback to NBT
    const pd = getPickaxeData(itemStack);
    pd.durability = (pd.durability || itemStack.maxDurability) - amount;
    if (pd.durability < 0) pd.durability = 0;
    setPickaxeData(itemStack, pd);
  }
}

function pulseNearbyOreParticles(world, playerPos, echoLevel) {
  // For each ore within radius R, spawn particle at approximate location. R scales with echoLevel.
  const R = 6 + echoLevel * 4;
  if (typeof world.findBlocksWithinRadius !== "function") {
    // fallback console
    console.log("Pulse ore particles around", playerPos, "radius", R);
    return;
  }
  const ores = world.findBlocksWithinRadius(playerPos.x, playerPos.y, playerPos.z, R, function(b) {
    return isBlockOre(b);
  });
  ores.forEach(o => {
    if (typeof world.spawnParticle === "function") {
      world.spawnParticle("enchant", o.x + 0.5, o.y + 0.5, o.z + 0.5);
    }
  });
}

/* =========================
   GUI: Implementation sketch for the Trench Enchanter interactive UI
   =========================
   Note: Real GUI implementation depends on platform. Below is a working pseudo-logic
   to show how to handle sliders, point budgeting, apply/cancel and NBT persistence.
   ========================= */

function openTrenchEnchanterForPlayer(player, blockPos) {
  // Get held item in player's hand
  const heldItem = player.getHeldItem ? player.getHeldItem() : player.itemInHand;
  if (!heldItem) {
    sendMessage(player, "You must hold a Trench Pickaxe to enchant it.");
    return;
  }
  if (Object.values(IDS.pickaxes).indexOf(heldItem.id) === -1) {
    sendMessage(player, "You must hold a Trench Pickaxe to use the Trench Enchanter.");
    return;
  }

  const guiInfo = createTrenchEnchanterGui(player, heldItem);
  // The GUI runtime should present interactive sliders and call back to us on events.
  // We'll register callback handlers in a pseudo-fashion.

  openGui(player, {
    title: guiInfo.guiDef.title,
    subtitle: "Points: 0 / " + guiInfo.maxPoints,
    width: guiInfo.guiDef.width,
    height: guiInfo.guiDef.height,
    elements: guiInfo.guiDef.elements,
    note: guiInfo.guiDef.note,
    onSliderChange: function(playerState, enchantId, newValue) {
      // playerState: {selectedLevels: {enchId: level, ...}}
      playerState.selectedLevels = playerState.selectedLevels || {};
      playerState.selectedLevels[enchantId] = newValue;
      // Recompute total used points
      const used = computePointsUsed(playerState.selectedLevels);
      // Push an update to the GUI (pseudo)
      return { used: used, max: guiInfo.maxPoints, ok: used <= guiInfo.maxPoints };
    },
    onApply: function(playerState) {
      const selected = playerState.selectedLevels || {};
      const used = computePointsUsed(selected);
      if (used > guiInfo.maxPoints) {
        sendMessage(player, "Selected enchant levels exceed this pickaxe's point budget (" + used + " > " + guiInfo.maxPoints + ").");
        return { success: false, message: "Not enough points." };
      }
      // Persist enchants to the held item NBT
      const pd = getPickaxeData(heldItem);
      pd.enchants = pd.enchants || {};
      Object.keys(selected).forEach(eid => {
        const lvl = selected[eid] || 0;
        if (lvl <= 0) delete pd.enchants[eid];
        else pd.enchants[eid] = lvl;
      });
      setPickaxeData(heldItem, pd);
      // Optionally consume player XP or items as cost. If no XP support, require trench_gem_green as cost (example).
      // For simplicity here, we do not consume XP in code; adapt as needed.
      sendMessage(player, "Applied trench enchants. Points used: " + used + " / " + guiInfo.maxPoints);
      return { success: true };
    },
    onCancel: function() {
      sendMessage(player, "Trench Enchanter: cancelled.");
      return { success: true };
    }
  });
}

function computePointsUsed(selectedLevels) {
  selectedLevels = selectedLevels || {};
  let total = 0;
  for (let i = 0; i < CUSTOM_ENCHANTS.length; i++) {
    const e = CUSTOM_ENCHANTS[i];
    const lvl = selectedLevels[e.id] || 0;
    total += lvl * e.costPerLevel;
  }
  return total;
}

